def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-dir", type=Path, default=Path("experiments/kbound/results/task4_matched_sar_v1"))
    parser.add_argument("--latex-out", type=Path, default=ROOT / "docs/research/kbound/paper/generated/tab_task4_matched_sar.tex")
    args = parser.parse_args()

    manifest_path = args.results_dir / "TASK4_MATCHED_SAR_MANIFEST.json"
    kga_path = args.results_dir / "TASK4_MATCHED_SAR_KGA_SUMMARY.json"

    if not manifest_path.exists():
        raise FileNotFoundError(f"Manifest not found: {manifest_path}")
    if not kga_path.exists():
        raise FileNotFoundError(f"KGA summary not found: {kga_path}")

    manifest = json.loads(manifest_path.read_text())
    kga_summary = json.loads(kga_path.read_text())

    generate_latex_table(manifest, kga_summary, args.latex_out)
    md_out = args.results_dir / "TASK4_MATCHED_SAR_SUMMARY.md"
    generate_markdown_summary(manifest, kga_summary, md_out)


if __name__ == "__main__":
    main()
