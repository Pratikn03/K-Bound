    comb_effect = a5.get("mean_candidate_accuracy", 0) - a2.get("mean_candidate_accuracy", 0)
    bn_vs_sar = a2.get("mean_candidate_accuracy", 0) - a1.get("mean_candidate_accuracy", 0)

