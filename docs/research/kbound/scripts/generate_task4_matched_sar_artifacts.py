        f"- **Rate-Only (Arm 3, $\\eta=4.0\\times 10^{{-3}}$, layers 1–3 affine, layer 4 frozen):** Cand Acc = {a3.get('mean_candidate_accuracy', 0)*100:.2f}%, $\\Delta = {a3.get('mean_candidate_benefit', 0)*100:+.2f}%$, Update Norm = {a3.get('mean_update_norm', 0):.4f}.",
