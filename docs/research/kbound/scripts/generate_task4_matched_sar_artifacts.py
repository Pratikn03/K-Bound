        f"- **Finding:** When BatchNorm statistics are configured faithfully, increasing learning rate 16-fold from $2.5\\times 10^{{-4}}$ to $4.0\\times 10^{{-3}}$ does not induce model collapse. Update norm scales from {a2.get('mean_update_norm', 0):.4f} to {a3.get('mean_update_norm', 0):.4f}, while candidate accuracy remains virtually unchanged ({a3.get('mean_candidate_accuracy', 0)*100:.2f}% vs {a2.get('mean_candidate_accuracy', 0)*100:.2f}%).",
