from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[4]

ARM_CONFIGS = {
    "arm1": {"label": "BN-only (zero grad)", "lr": "--", "lr_md": "$0.0$", "mask": "None", "bn": "Test Stats"},
    "arm2": {"label": "SAR reference parameters; local execution", "lr": r"$2.5\times 10^{-4}$", "lr_md": r"$2.5\times 10^{-4}$", "mask": "Layers 1--3", "bn": "Test Stats"},
    "arm3": {"label": "Rate only", "lr": r"$4.0\times 10^{-3}$", "lr_md": r"$4.0\times 10^{-3}$", "mask": "Layers 1--3", "bn": "Test Stats"},
    "arm4": {"label": "Mask only", "lr": r"$2.5\times 10^{-4}$", "lr_md": r"$2.5\times 10^{-4}$", "mask": "Layers 1--4", "bn": "Test Stats"},
    "arm5": {"label": "Historical combined", "lr": r"$4.0\times 10^{-3}$", "lr_md": r"$4.0\times 10^{-3}$", "mask": "Layers 1--4", "bn": "Test Stats"},
}


def generate_latex_table(manifest: dict[str, Any], kga_summary: dict[str, Any], out_path: Path):
    lines = [
        r"% AUTO-GENERATED by generate_task4_matched_sar_artifacts.py. Do not edit by hand.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\small",
        r"\caption{\textbf{Matched SAR Control Study on ImageNet-C.} Five-arm matched ablation varying learning rate $\eta$ and parameter mask (with layer 4 frozen vs adapted) on a shared 27-condition ImageNet-C noise panel ($n=27$ cells, ResNet-50 source checkpoint, small batch regime $b=16$, seed 0). Candidate accuracy $a_{\mathrm{cand}}$, benefit $\Delta = a_{\mathrm{cand}} - a_0$, parameter update norm $\|\Delta \theta\|_2$, Protocol~B KGA routed accuracy $a_{\mathrm{KGA}}$, oracle regret $R_{\mathrm{KGA}}$, unconditional false adapt rate $\mathrm{FA}_u$, and decision counts (Adapt / Freeze / Abstain) under exact rank conformal routing ($\alpha=0.10, \tau=0$). Always Freeze regret is $3.30$--$3.31\,\text{pp}$ across arms ($3.30\,\text{pp}$ for Arms 1--4, $3.31\,\text{pp}$ for Arm 5); Always Adapt regret is $0.00\,\text{pp}$. Accuracy is reported as a percentage; benefit $\Delta$ and regret are reported in percentage points. Saved records support these comparisons; complete execution identities remain unavailable. Per-condition records and declared execution fields are indexed by \texttt{task4\_matched\_sar\_v1/TASK4\_MATCHED\_SAR\_MANIFEST.json}.}",
        r"\label{tab:task4_matched_sar}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{@{}llccccccccc@{}}",
        r"\toprule",
        r"\textbf{Arm} & \textbf{Configuration} & $\mathbf{\eta}$ & \textbf{Adapted Layers} & $\mathbf{a_{\mathrm{cand}}}$ & $\mathbf{\Delta}$ & $\mathbf{\|\Delta\theta\|_2}$ & $\mathbf{a_{\mathrm{KGA}}}$ & $\mathbf{R_{\mathrm{KGA}}}$ & $\mathbf{FA_u}$ & \textbf{Decisions (A/F/Abs)} \\",
        r"\midrule",
    ]

    for ak, cfg in ARM_CONFIGS.items():
        if ak not in manifest.get("arm_summaries", {}):
            raise KeyError(f"Missing required arm summary for {ak} in manifest")
        if ak not in kga_summary:
            raise KeyError(f"Missing required KGA summary for {ak}")

        sum_m = manifest["arm_summaries"][ak]
        kga_m = kga_summary[ak]["routing_metrics"]
        
        a_cand = sum_m["mean_candidate_accuracy"] * 100.0
        delta = sum_m["mean_candidate_benefit"] * 100.0
        norm = sum_m["mean_update_norm"]
        
        a_kga = kga_m["mean_kga_accuracy"] * 100.0
        r_kga = kga_m["mean_kga_oracle_regret"] * 100.0
        fa_u = kga_m["unconditional_false_adapt_rate"] * 100.0
        
        df = kga_m["decision_counts"]
        dec_str = f"{df['ADAPT']}/{df['FREEZE']}/{df['ABSTAIN']}"

        arm_num = ak.replace("arm", "Arm ")
        lines.append(
            f"{arm_num} & {cfg['label']} & {cfg['lr']} & {cfg['mask']} & "
            f"{a_cand:.2f}\\% & {delta:+.2f}\\% & {norm:.4f} & "
            f"{a_kga:.2f}\\% & {r_kga:.2f}\\% & {fa_u:.1f}\\% & {dec_str} \\\\"
        )

    lines.extend([
        r"\bottomrule",
        r"\end{tabular}%",
        r"}",
        r"\end{table*}",
        "",
    ])

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines))
    print(f"LaTeX table generated: {out_path}")


def generate_markdown_summary(manifest: dict[str, Any], kga_summary: dict[str, Any], out_path: Path):
    arms = manifest.get("arm_summaries", {})
    a1 = arms.get("arm1", {})
    a2 = arms.get("arm2", {})
    a3 = arms.get("arm3", {})
    a4 = arms.get("arm4", {})
    a5 = arms.get("arm5", {})

    k1 = kga_summary.get("arm1", {}).get("routing_metrics", {})
    k2 = kga_summary.get("arm2", {}).get("routing_metrics", {})
    k3 = kga_summary.get("arm3", {}).get("routing_metrics", {})
    k4 = kga_summary.get("arm4", {}).get("routing_metrics", {})
    k5 = kga_summary.get("arm5", {}).get("routing_metrics", {})

    lr_effect = a3.get("mean_candidate_accuracy", 0) - a2.get("mean_candidate_accuracy", 0)
