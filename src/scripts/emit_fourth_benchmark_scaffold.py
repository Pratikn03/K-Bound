"""Emit the fourth-paired-benchmark scaffold table.

Phase-D task D.1 (REVIEWER_RATING_AND_PHASE_PLAN.md) asks for a
*fourth* naturally paired benchmark beyond MVTec 3D-AD, MVTec
LOCO-AD / VisA, and UNSW-NB15. Candidate datasets named by the
reviewer:

  - CICIDS-2017 paired with authentication logs (network + auth)
  - MIMIC-IV paired with clinical notes (vitals + text)
  - PADIM-on-MVTec-AD-2D paired with depth (alternative industrial)

This script does NOT run a fourth benchmark. It emits a "results
pending" table the paper can include so the reviewer can see the
plan and the explicit non-fabrication of numbers. The table is
auto-generated from a single source of truth (the CANDIDATES list
below); replacing a row's status from "pending" to a real number is
the only step required when actual results land.
"""

from __future__ import annotations

import argparse
from pathlib import Path

GENERATED_COMMENT = "% Auto-generated by emit_fourth_benchmark_scaffold.py (do not edit by hand)"

CANDIDATES = [
    {
        "dataset": "CICIDS-2017 + auth logs",
        "modalities": "network flows + authentication events",
        "pairing_key": "session id within window",
        "size": "$\\sim$2.8M flows",
        "status": "pending",
        "notes": "public license; auth log integration scripted but not yet executed",
    },
    {
        "dataset": "MIMIC-IV + clinical notes",
        "modalities": "vitals timeseries + free-text notes",
        "pairing_key": "patient stay id",
        "size": "$\\sim$73k ICU stays",
        "status": "pending",
        "notes": "credentialed access required; pairing schema drafted",
    },
    {
        "dataset": "MVTec AD-2D + depth pseudo",
        "modalities": "RGB texture + synthetic depth",
        "pairing_key": "category + frame id",
        "size": "$\\sim$5{,}000 frames",
        "status": "pending",
        "notes": "depth pseudo-channel deliberately weaker than MVTec 3D-AD",
    },
]


def render_table() -> str:
    rows = [
        GENERATED_COMMENT,
        r"\begin{tabular}{p{0.18\textwidth}p{0.24\textwidth}p{0.18\textwidth}p{0.10\textwidth}p{0.10\textwidth}p{0.18\textwidth}}",
        r"\toprule",
        r"\textbf{Dataset} & \textbf{Modalities} & \textbf{Pairing key} & "
        r"\textbf{Size} & \textbf{Status} & \textbf{Notes} \\",
        r"\midrule",
    ]
    for r in CANDIDATES:
        rows.append(
            rf"{r['dataset']} & {r['modalities']} & {r['pairing_key']} & "
            rf"{r['size']} & \emph{{{r['status']}}} & {r['notes']} \\"
        )
    rows += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("docs/research/tables/fourth_benchmark_scaffold.tex"),
    )
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_table(), encoding="utf-8")
    print(f"Wrote {args.output}")
    print(render_table())


if __name__ == "__main__":
    main()
