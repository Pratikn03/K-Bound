"""Emit the thesis theory-to-experiment mapping table from the theorem registry."""

from __future__ import annotations

import argparse
from pathlib import Path

from elara.theory.theorem_registry import THEOREM_REGISTRY, artifact_status

GENERATED_COMMENT = "% Auto-generated by emit_theory_experiment_mapping.py (do not edit by hand)"


def _exists(repo_root: Path, rel: str) -> bool:
    return (repo_root / rel).exists()


def _mapping_rows(repo_root: Path) -> list[tuple[str, str, str]]:
    t2_synthetic = _exists(repo_root, "docs/research/tables/category_mixture_t2.tex")
    t2_real = _exists(repo_root, "experiments/phase2/mechanism/domain_composition_shift_metrics.csv")
    t3 = _exists(repo_root, "docs/research/tables/elara_k_domain_corruption_results.tex")
    t4 = _exists(repo_root, "docs/research/tables/risk_dominance_t4_prevalence.tex")
    t5 = _exists(repo_root, "docs/research/tables/switching_certificate_t5.tex")
    t6 = _exists(repo_root, "docs/research/tables/ks_power_t6.tex")
    t7 = _exists(repo_root, "docs/research/tables/meta_router_pac_t7.tex")
    gdr = _exists(repo_root, "docs/research/tables/gate_decision_rule_e2e.tex")

    rows: list[tuple[str, str, str]] = [
        (
            "T1 quality-blind impossibility",
            "Architectural motivation: score-only fusion cannot disambiguate identical score vectors with different latent reliability states.",
            "Formal example is theoretical; no separate empirical table is needed beyond collapse construction.",
        ),
        (
            "T2 global-KS mixture confounding",
            (
                "Synthetic mixture-shift table confirms global KS $\\gg$ category-conditional KS at all five seeds."
                if t2_synthetic
                else "Category-aware reference experiments show global references can over-activate under heterogeneous categories."
            ),
            (
                "Real cohort/domain composition shift (B-MECH-3S) remains deferred: both global and domain-aware gates fired at rate 1.000."
                if t2_real
                else "Needs a pure controlled mixture-shift table with no within-category corruption."
            ),
        ),
        (
            "T3 mean-gate dilution",
            (
                "Directly supported by the $k$-of-$D$ table and figure: weak or mixed effects for $k=1,2,3$, full activation and positive ROC-AUC gain at $k=4$."
                if t3
                else "Awaiting k-of-$D$ corruption table regeneration."
            ),
            "The ideal theorem assumes failed-domain reliability is zero; the implemented estimator keeps minimum reliability above $0.34$.",
        ),
        (
            "T4 risk dominance",
            (
                "Deployment-prevalence sensitivity table reports $(q_0,q_1,\\Delta_0,\\Delta_1,\\pi^{*})$ and the dominance margin at $\\pi\\in\\{0,0.01,\\ldots,0.5\\}$."
                if t4
                else "The theorem gives measurable terms $(q_0,q_1,\\Delta_0,\\Delta_1)$ for when switching should win."
            ),
            "Retrospective B-CERT-1 estimate only; not a production prevalence audit.",
        ),
        (
            "T5 finite-sample certificate",
            (
                "Audited deployment-window LCB table certifies seven of ten benchmark/protocol pairs (see switching-certificate table)."
                if t5
                else "Certificate utility exists and defines fired-case paired benefit."
            ),
            "Retrospective evaluation certificate under defined stress protocol; not a production safety guarantee.",
        ),
        (
            "T6 KS false-fire/power",
            (
                "KS window sweep reports false-activation rate and detection power on the locked grid (32--512)."
                if t6
                else "KS is the empirically necessary trigger in component ablation."
            ),
            "Bounded to the evaluated window grid and degradation types; not a full calibrated drift-detection claim.",
        ),
        (
            "T7 PAC meta-router",
            (
                "PAC slack table reports auditable $(n,B,R)$ bounds per meta-router fold."
                if t7
                else "PAC audit JSON exists; table not yet emitted."
            ),
            "Capacity certificate on the router only; composes with T1/T2/T6 rather than proving fusion dominance.",
        ),
    ]
    if gdr:
        rows.append(
            (
                "GDR coherence-certified rule",
                "End-to-end audit shows the rule allows switching under coherent collapse (Family B proxy) and suppresses it under heterogeneous mixtures (Family D proxy).",
                "Forward/opt-in policy; does not alter locked Phase-2 numbers.",
            )
        )
    return rows


def render(repo_root: Path) -> str:
    out = [
        GENERATED_COMMENT,
        r"\begin{tabular}{p{0.16\textwidth}p{0.35\textwidth}p{0.38\textwidth}}",
        r"\toprule",
        r"\textbf{Claim} & \textbf{Current evidence} & \textbf{Boundary still open} \\",
        r"\midrule",
    ]
    for claim, evidence, boundary in _mapping_rows(repo_root):
        out.append(rf"{claim} & {evidence} & {boundary} \\")
    out += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parents[2],
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("docs/research/tables/elara_theory_experiment_mapping.tex"),
    )
    args = parser.parse_args()
    table = render(args.repo_root)
    out_path = args.repo_root / args.output if not args.output.is_absolute() else args.output
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(table, encoding="utf-8")
    print(f"Wrote {out_path}")
    for spec_id, spec in THEOREM_REGISTRY.items():
        status = artifact_status(args.repo_root, spec)
        if spec.artifact_paths:
            missing = [p for p, ok in status.items() if not ok]
            if missing:
                print(f"  {spec_id}: missing {missing}")


if __name__ == "__main__":
    main()
