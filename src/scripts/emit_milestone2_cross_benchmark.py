"""Emit the cross-benchmark master comparison table — Phase 1 audited reanalysis.

This emit script is the manuscript's primary master comparison table. After
Phase 1.B / 1.C / 1.D it reads from three locked artifacts:

  - experiments/audit/rga_plus_validation_frozen_selection.csv
      (validation-frozen RGA+ head per cell)
  - experiments/audit/audited_comparator_selection.csv
      (validation-frozen primary comparator per cell)
  - experiments/audit/audited_ensemble_inference_results.csv
      (single-representative-seed DeLong + Holm-corrected p per Family A cell)

Forbidden under Phase 1 (the rewrite removed all three):
  - selecting the RGA+ headline by reading the test fold
  - selecting the comparator by an argmax over baselines' test ROC-AUC
  - Fisher combination of per-seed DeLong p-values

Caption fields explicitly reported:
  - RGA+ head = validation-frozen choice per cell
  - Primary comparator = validation-frozen choice per cell
  - Inference = single-representative-seed DeLong (seed 42)
  - Holm correction = applied within Family A audited-primary cells (K=5)
  - Cells outside Family A confirmatory are descriptive only
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path

GENERATED_COMMENT = "% Auto-generated by emit_milestone2_cross_benchmark.py — Phase 1 locked audited reanalysis."

# Display label for each known method.
METHOD_LABELS = {
    "router": "router",
    "boost": "boost",
    "random_forest": "RF",
    "early_fusion_mlp": "MLP",
    "late_fusion_ensemble": "LFE",
    "confidence_weighted_mean": "Conf-mean",
    "tent_score_adapter": "Tent",
    "ttt_pseudo_label_adapter": "TTT",
    "eata_score_adapter": "EATA",
    "sar_score_adapter": "SAR",
}

# Display order — Family A first, then Family C exploratory.
DISPLAY_ORDER = [
    ("A1", "MVTec 3D-AD", "PatchCore canonical"),
    ("A2", "MVTec 3D-AD", "PatchCore supervised"),
    ("A3", "MVTec 3D-AD", "PatchCore held-out"),
    ("A4", "MVTec LOCO-AD", "PatchCore canonical"),
    ("A5", "MVTec LOCO-AD", "PatchCore supervised"),
    ("A6", "VisA", "RGB+edge canonical"),
    ("A7", "VisA", "RGB+edge supervised"),
    ("A8", "UNSW-NB15", "flow/conn/context"),
    ("C1", "Real3D-AD", "PCA shape + depth supervised"),
    ("C2", "VisA", "RGB+random noise-floor"),
    ("C3", "UNSW-NB15", "held-out attack categories"),
]


def _fmt(value, decimals: int = 3) -> str:
    if value is None or value == "":
        return "--"
    try:
        v = float(value)
    except (TypeError, ValueError):
        return "--"
    if not math.isfinite(v):
        return "--"
    return f"{v:.{decimals}f}"


def _fmt_signed(value, decimals: int = 3) -> str:
    if value is None or value == "":
        return "--"
    try:
        v = float(value)
    except (TypeError, ValueError):
        return "--"
    if not math.isfinite(v):
        return "--"
    return f"{v:+.{decimals}f}"


def _fmt_p(value) -> str:
    if value is None or value == "":
        return "--"
    try:
        v = float(value)
    except (TypeError, ValueError):
        return "--"
    if not math.isfinite(v):
        return "--"
    if v < 1e-3:
        return f"{v:.1e}"
    return f"{v:.3f}"


def _load_csv(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open() as f:
        return list(csv.DictReader(f))


def _idx_by_cell(rows: list[dict], key: tuple[str, str], extra_filter=None) -> dict | None:
    bm, proto = key
    for r in rows:
        if extra_filter is not None and not extra_filter(r):
            continue
        if r.get("benchmark") == bm and r.get("protocol") == proto:
            return r
    return None


def _static_rga_from_json(repo_root: Path, benchmark: str, protocol: str) -> tuple[float | None, float | None]:
    """Pull static_attention and craf_attention seed-mean ROC-AUC from the cell's JSON."""
    json_paths = {
        ("MVTec 3D-AD", "PatchCore canonical"): "experiments/fusion/mvtec3d_patchcore_results.json",
        ("MVTec 3D-AD", "PatchCore supervised"): "experiments/fusion/mvtec3d_patchcore_supervised_paired_results.json",
        ("MVTec 3D-AD", "PatchCore held-out"): "experiments/fusion/mvtec3d_patchcore_heldout_results.json",
        ("MVTec LOCO-AD", "PatchCore canonical"): "experiments/fusion/mvtec_loco_patchcore_results.json",
        (
            "MVTec LOCO-AD",
            "PatchCore supervised",
        ): "experiments/fusion/mvtec_loco_patchcore_supervised_paired_results.json",
        ("Real3D-AD", "PCA shape + depth supervised"): "experiments/fusion/real3d_supervised_paired_results.json",
        ("VisA", "RGB+edge canonical"): "experiments/fusion/visa_fusion_results.json",
        ("VisA", "RGB+edge supervised"): "experiments/fusion/visa_supervised_paired_results.json",
        ("VisA", "RGB+random noise-floor"): "experiments/fusion/visa_supervised_paired_noise_floor_results.json",
        ("UNSW-NB15", "flow/conn/context"): "experiments/fusion/unsw_paired_results.json",
        ("UNSW-NB15", "held-out attack categories"): "experiments/fusion/unsw_heldout_attack_results.json",
    }
    rel = json_paths.get((benchmark, protocol))
    if rel is None:
        return None, None
    p = repo_root / rel
    if not p.exists():
        return None, None
    payload = json.loads(p.read_text())
    cs = payload.get("clean_metric_summary", {})

    def _m(name):
        d = cs.get(name, {}).get("roc_auc")
        if isinstance(d, dict):
            return d.get("mean")
        return d if isinstance(d, (int, float)) else None

    return _m("static_attention"), _m("craf_attention")


def render_table(repo_root: Path) -> str:
    rga_rows = _load_csv(repo_root / "experiments/audit/rga_plus_validation_frozen_selection.csv")
    comp_rows = _load_csv(repo_root / "experiments/audit/audited_comparator_selection.csv")
    inf_rows = _load_csv(repo_root / "experiments/audit/audited_ensemble_inference_results.csv")

    rga_idx_ensemble = [r for r in rga_rows if r.get("seed_or_ensemble") == "ensemble"]

    lines = [
        GENERATED_COMMENT,
        r"\begin{tabular}{llccccccccc}",
        r"\toprule",
        (
            r"\textbf{Cell} & \textbf{Benchmark / Protocol} & \textbf{Family} & "
            r"\textbf{Static} & \textbf{RGA} & "
            r"\textbf{RGA+ (val-frozen)} & \textbf{Head} & "
            r"\textbf{Primary comparator (val-frozen)} & "
            r"\textbf{$\Delta$ AUC} & \textbf{$p$ (rep seed)} & \textbf{$p_{\mathrm{Holm}}$ (A K=5)} \\"
        ),
        r"\midrule",
    ]

    for cell_id, benchmark, protocol in DISPLAY_ORDER:
        rga = _idx_by_cell(rga_idx_ensemble, (benchmark, protocol))
        comp = _idx_by_cell(comp_rows, (benchmark, protocol))
        inf = _idx_by_cell(inf_rows, (benchmark, protocol))

        static_v, rga_v = _static_rga_from_json(repo_root, benchmark, protocol)

        rga_head = rga.get("selected_head") if rga else None
        rga_test = rga.get("selected_test_auc") if rga else None
        comp_name = comp.get("selected_comparator") if comp else None
        comp_test = comp.get("selected_comparator_test_auc") if comp else None
        delta = None
        if isinstance(rga_test, str):
            try:
                rga_test_f = float(rga_test)
            except (TypeError, ValueError):
                rga_test_f = None
        else:
            rga_test_f = rga_test
        if isinstance(comp_test, str):
            try:
                comp_test_f = float(comp_test)
            except (TypeError, ValueError):
                comp_test_f = None
        else:
            comp_test_f = comp_test
        if isinstance(rga_test_f, (int, float)) and isinstance(comp_test_f, (int, float)):
            delta = float(rga_test_f) - float(comp_test_f)

        p_raw = inf.get("delong_p_raw_single_rep_seed") if inf else None
        p_holm = inf.get("delong_p_holm_if_applicable") if inf else None

        head_label = METHOD_LABELS.get(rga_head, rga_head or "--")
        comp_label = METHOD_LABELS.get(comp_name, comp_name or "--")
        family_label = cell_id[0]

        lines.append(
            rf"{cell_id} & {benchmark} / {protocol} & {family_label} & "
            rf"{_fmt(static_v)} & {_fmt(rga_v)} & "
            rf"{_fmt(rga_test_f)} & {head_label} & "
            rf"{comp_label} ({_fmt(comp_test_f)}) & "
            rf"{_fmt_signed(delta)} & {_fmt_p(p_raw)} & {_fmt_p(p_holm)} \\"
        )

    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("docs/research/tables/milestone2_cross_benchmark.tex"),
    )
    parser.add_argument("--repo-root", type=Path, default=Path("."))
    args = parser.parse_args()

    table = render_table(args.repo_root)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(table, encoding="utf-8")
    print(f"Wrote {args.output}")
    print(table)


if __name__ == "__main__":
    main()
