"""Emit the Milestone-2 cross-benchmark summary table.

Joins results from every naturally-paired ELARA benchmark into a single
LaTeX table so reviewers can see the cross-domain consistency of
RGA / RGA+ in one place. Rows currently rendered when the JSON exists:

  - MVTec 3D-AD       (PatchCore + canonical one-class)
  - MVTec 3D-AD       (PatchCore + supervised paired)
  - MVTec 3D-AD       (PatchCore + held-out category)
  - MVTec LOCO-AD     (PatchCore + canonical)              [A1, when downloaded]
  - Real3D-AD         (FPFH + depth projection)           [A2, when downloaded]
  - VisA              (PatchCore + depth-proxy)           [A3, when downloaded]
  - UNSW-NB15 paired  (flow + connection + context)        [A4]
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any

from scipy.stats import chi2

GENERATED_COMMENT = "% Auto-generated by emit_milestone2_cross_benchmark.py (do not edit by hand)"


def _fisher_combine(p_values: list[float]) -> float:
    """Fisher's combined p-value: -2 * sum(log p) ~ chi-square(2k).

    Skips NaN entries. Returns NaN when no valid p-values are present.
    Clips individual p-values at 1e-300 to avoid log(0).
    """
    finite = [
        float(p)
        for p in p_values
        if p is not None and isinstance(p, (int, float)) and math.isfinite(float(p))
    ]
    if not finite:
        return float("nan")
    clipped = [max(p, 1e-300) for p in finite]
    chi_stat = -2.0 * sum(math.log(p) for p in clipped)
    df = 2 * len(clipped)
    return float(1.0 - chi2.cdf(chi_stat, df))


def _holm_bonferroni(p_values: dict[Any, float]) -> dict[Any, float]:
    """Holm-Bonferroni step-down correction.

    Sorted by ascending raw p; adjusted p_k = min(1, max so-far(p_k * (K - k + 1))).
    NaN entries are preserved as NaN and excluded from the K count.
    Returns a mapping keyed identically to the input.
    """
    finite_items = [
        (key, float(p))
        for key, p in p_values.items()
        if p is not None and isinstance(p, (int, float)) and math.isfinite(float(p))
    ]
    finite_items.sort(key=lambda kv: kv[1])
    K = len(finite_items)
    adjusted: dict[Any, float] = {}
    running = 0.0
    for rank, (key, raw_p) in enumerate(finite_items, start=1):
        candidate = min(1.0, raw_p * (K - rank + 1))
        running = max(running, candidate)
        adjusted[key] = running
    for key, p in p_values.items():
        if key not in adjusted:
            adjusted[key] = float("nan") if (p is None or not isinstance(p, (int, float)) or not math.isfinite(float(p))) else float(p)
    return adjusted


def _fmt(value: float | None, decimals: int = 3) -> str:
    if value is None or (isinstance(value, float) and value != value):
        return "--"
    try:
        return f"{float(value):.{decimals}f}"
    except (TypeError, ValueError):
        return "--"


def _dig(payload: dict | None, *keys: str) -> Any:
    for key in keys:
        if payload is None:
            return None
        payload = payload.get(key)
    return payload


def _method_label(name: str | None) -> str:
    labels = {
        "random_forest": "RF",
        "confidence_weighted_mean": "Conf-mean",
        "tent_score_adapter": "Tent",
        "ttt_pseudo_label_adapter": "TTT",
        "eata_score_adapter": "EATA",
        "sar_score_adapter": "SAR",
        "early_fusion_mlp": "MLP",
        "late_fusion_ensemble": "LFE",
        "static_attention": "Static",
        "craf_attention": "RGA",
    }
    return labels.get(str(name), str(name or "--"))


def _cell(payload: dict) -> dict[str, float | str | None]:
    cs = payload.get("clean_metric_summary", {})
    static = _dig(cs, "static_attention", "roc_auc", "mean")
    rga = _dig(cs, "craf_attention", "roc_auc", "mean")
    rga_router = _dig(cs, "rga_meta_router", "roc_auc", "mean")
    rga_boost = _dig(cs, "rga_boosted_fusion", "roc_auc", "mean")
    # Best RGA+ variant for cross-benchmark headline.
    rga_plus_candidates = [v for v in (rga_router, rga_boost) if v is not None]
    rga_plus = max(rga_plus_candidates) if rga_plus_candidates else None
    if rga_plus is None or (rga_boost is not None and rga_boost == rga_plus):
        rga_plus_variant = "boost"
    else:
        rga_plus_variant = "router"
    rga_plus_method_name = (
        "rga_boosted_fusion" if rga_plus_variant == "boost" else "rga_meta_router"
    )
    best_name = None
    best_roc = None
    for name, metrics in cs.items():
        if name in {"craf_attention", "rga_boosted_fusion", "rga_meta_router"}:
            continue
        roc = _dig(metrics, "roc_auc", "mean")
        if roc is None:
            continue
        if best_roc is None or float(roc) > float(best_roc):
            best_name = name
            best_roc = roc

    # Fisher-combine DeLong p (RGA+ vs best non-router) across seeds.
    per_seed = payload.get("table_1_clean_performance", []) or []
    delong_seed_ps: list[float] = []
    for seed_row in per_seed:
        pair_dict = (
            seed_row.get("delong_p_rga_plus_vs_baseline", {})
            .get(rga_plus_method_name, {})
        )
        p = pair_dict.get(best_name) if best_name else None
        if p is None or not isinstance(p, (int, float)) or not math.isfinite(float(p)):
            continue
        delong_seed_ps.append(float(p))
    delong_fisher_p = _fisher_combine(delong_seed_ps) if delong_seed_ps else float("nan")

    return {
        "static": static,
        "rga": rga,
        "rga_plus": rga_plus,
        "rga_plus_variant": rga_plus_variant,
        "rga_plus_method_name": rga_plus_method_name,
        "delta_plus_vs_best": (rga_plus - best_roc) if (rga_plus is not None and best_roc is not None) else None,
        "best_name": _method_label(best_name),
        "best_method_key": best_name,
        "best_roc": best_roc,
        "delong_p_seed_values": delong_seed_ps,
        "delong_fisher_p": delong_fisher_p,
    }


BENCHMARKS = [
    ("MVTec 3D-AD", "PatchCore canonical", "experiments/fusion/mvtec3d_patchcore_results.json"),
    ("MVTec 3D-AD", "PatchCore supervised", "experiments/fusion/mvtec3d_patchcore_supervised_paired_results.json"),
    ("MVTec 3D-AD", "PatchCore held-out", "experiments/fusion/mvtec3d_patchcore_heldout_results.json"),
    ("MVTec LOCO-AD", "PatchCore canonical", "experiments/fusion/mvtec_loco_patchcore_results.json"),
    ("MVTec LOCO-AD", "PatchCore supervised", "experiments/fusion/mvtec_loco_patchcore_supervised_paired_results.json"),
    ("Real3D-AD", "FPFH+depth supervised", "experiments/fusion/real3d_supervised_paired_results.json"),
    ("VisA", "RGB+edge canonical", "experiments/fusion/visa_fusion_results.json"),
    ("VisA", "RGB+edge supervised", "experiments/fusion/visa_supervised_paired_results.json"),
    ("VisA", "RGB+random noise-floor", "experiments/fusion/visa_supervised_paired_noise_floor_results.json"),
    ("UNSW-NB15", "flow/conn/context", "experiments/fusion/unsw_paired_results.json"),
    ("UNSW-NB15", "held-out attack categories", "experiments/fusion/unsw_heldout_attack_results.json"),
]


def _fmt_p(p: float | None) -> str:
    """Format a p-value with scientific notation for very small p."""
    if p is None or not isinstance(p, (int, float)) or not math.isfinite(float(p)):
        return "--"
    if float(p) < 1e-3:
        return f"{float(p):.1e}"
    return f"{float(p):.3f}"


def render_table(repo_root: Path) -> str:
    rendered_rows: list[tuple[str, str, dict[str, Any] | None, Path]] = []
    for benchmark, protocol, rel_path in BENCHMARKS:
        full_path = repo_root / rel_path
        if not full_path.exists():
            rendered_rows.append((benchmark, protocol, None, full_path))
            continue
        payload = json.loads(full_path.read_text(encoding="utf-8"))
        rendered_rows.append((benchmark, protocol, _cell(payload), full_path))

    # Holm-Bonferroni across all available cells with a Fisher-combined p.
    raw_ps: dict[tuple[str, str], float] = {}
    for benchmark, protocol, cell, _ in rendered_rows:
        if cell is None:
            continue
        key = (benchmark, protocol)
        raw_ps[key] = cell["delong_fisher_p"]
    holm = _holm_bonferroni(raw_ps)

    rows = [
        GENERATED_COMMENT,
        r"\begin{tabular}{llcccccccc}",
        r"\toprule",
        r"\textbf{Benchmark} & \textbf{Protocol} & \textbf{Static} & \textbf{RGA} & \textbf{RGA+} & \textbf{Best non-router} & \textbf{Best ROC} & \textbf{$\Delta$ vs best} & \textbf{$p$ (DeLong, Fisher)} & \textbf{$p_{\mathrm{Holm}}$} \\",
        r"\midrule",
    ]
    for benchmark, protocol, cell, _ in rendered_rows:
        if cell is None:
            rows.append(
                rf"{benchmark} & {protocol} & \multicolumn{{8}}{{c}}{{\emph{{pending dataset download}}}} \\"
            )
            continue
        key = (benchmark, protocol)
        raw_p = cell["delong_fisher_p"]
        adj_p = holm.get(key)
        rows.append(
            rf"{benchmark} & {protocol} & "
            rf"{_fmt(cell['static'])} & {_fmt(cell['rga'])} & {_fmt(cell['rga_plus'])} & "
            rf"{cell['best_name']} & {_fmt(cell['best_roc'])} & "
            rf"{_fmt(cell['delta_plus_vs_best'])} & "
            rf"{_fmt_p(raw_p)} & {_fmt_p(adj_p)} \\"
        )
    rows += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("docs/research/tables/milestone2_cross_benchmark.tex"),
    )
    parser.add_argument("--repo-root", type=Path, default=Path("."))
    args = parser.parse_args()

    table = render_table(args.repo_root)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(table, encoding="utf-8")
    print(f"Wrote {args.output}")
    print(table)


if __name__ == "__main__":
    main()
