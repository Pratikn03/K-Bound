"""Emit the Milestone-2 cross-benchmark summary table.

Joins results from every naturally-paired ELARA benchmark into a single
LaTeX table so reviewers can see the cross-domain consistency of
RGA / RGA+ in one place. Rows currently rendered when the JSON exists:

  - MVTec 3D-AD       (PatchCore + canonical one-class)
  - MVTec 3D-AD       (PatchCore + supervised paired)
  - MVTec 3D-AD       (PatchCore + held-out category)
  - MVTec LOCO-AD     (PatchCore + canonical)              [A1, when downloaded]
  - Real3D-AD         (FPFH + depth projection)           [A2, when downloaded]
  - VisA              (PatchCore + depth-proxy)           [A3, when downloaded]
  - UNSW-NB15 paired  (flow + connection + context)        [A4]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

GENERATED_COMMENT = "% Auto-generated by emit_milestone2_cross_benchmark.py (do not edit by hand)"


def _fmt(value: float | None, decimals: int = 3) -> str:
    if value is None or (isinstance(value, float) and value != value):
        return "--"
    try:
        return f"{float(value):.{decimals}f}"
    except (TypeError, ValueError):
        return "--"


def _dig(payload: dict | None, *keys: str) -> Any:
    for key in keys:
        if payload is None:
            return None
        payload = payload.get(key)
    return payload


def _method_label(name: str | None) -> str:
    labels = {
        "random_forest": "RF",
        "confidence_weighted_mean": "Conf-mean",
        "tent_score_adapter": "Tent",
        "ttt_pseudo_label_adapter": "TTT",
        "early_fusion_mlp": "MLP",
        "late_fusion_ensemble": "LFE",
        "static_attention": "Static",
        "craf_attention": "RGA",
    }
    return labels.get(str(name), str(name or "--"))


def _cell(payload: dict) -> dict[str, float | str | None]:
    cs = payload.get("clean_metric_summary", {})
    static = _dig(cs, "static_attention", "roc_auc", "mean")
    rga = _dig(cs, "craf_attention", "roc_auc", "mean")
    rga_plus = _dig(cs, "rga_meta_router", "roc_auc", "mean")
    if rga_plus is None:
        rga_plus = _dig(cs, "rga_boosted_fusion", "roc_auc", "mean")
    best_name = None
    best_roc = None
    for name, metrics in cs.items():
        if name in {"craf_attention", "rga_boosted_fusion", "rga_meta_router"}:
            continue
        roc = _dig(metrics, "roc_auc", "mean")
        if roc is None:
            continue
        if best_roc is None or float(roc) > float(best_roc):
            best_name = name
            best_roc = roc
    return {
        "static": static,
        "rga": rga,
        "rga_plus": rga_plus,
        "delta_plus_vs_best": (rga_plus - best_roc) if (rga_plus is not None and best_roc is not None) else None,
        "best_name": _method_label(best_name),
        "best_roc": best_roc,
    }


BENCHMARKS = [
    ("MVTec 3D-AD", "PatchCore canonical", "experiments/fusion/mvtec3d_patchcore_results.json"),
    ("MVTec 3D-AD", "PatchCore supervised", "experiments/fusion/mvtec3d_patchcore_supervised_paired_results.json"),
    ("MVTec 3D-AD", "PatchCore held-out", "experiments/fusion/mvtec3d_patchcore_heldout_results.json"),
    ("MVTec LOCO-AD", "PatchCore canonical", "experiments/fusion/mvtec_loco_patchcore_results.json"),
    ("Real3D-AD", "FPFH+depth", "experiments/fusion/real3d_fusion_results.json"),
    ("VisA", "PatchCore+depth-proxy", "experiments/fusion/visa_fusion_results.json"),
    ("UNSW-NB15", "flow/connection/context", "experiments/fusion/unsw_paired_results.json"),
]


def render_table(repo_root: Path) -> str:
    rows = [
        GENERATED_COMMENT,
        r"\begin{tabular}{llcccccc}",
        r"\toprule",
        r"\textbf{Benchmark} & \textbf{Protocol} & \textbf{Static} & \textbf{RGA} & \textbf{RGA+} & \textbf{Best non-router} & \textbf{Best ROC} & \textbf{$\Delta$ vs best} \\",
        r"\midrule",
    ]
    for benchmark, protocol, rel_path in BENCHMARKS:
        full_path = repo_root / rel_path
        if not full_path.exists():
            rows.append(
                rf"{benchmark} & {protocol} & \multicolumn{{6}}{{c}}{{\emph{{pending dataset download}}}} \\"
            )
            continue
        payload = json.loads(full_path.read_text(encoding="utf-8"))
        cell = _cell(payload)
        rows.append(
            rf"{benchmark} & {protocol} & "
            rf"{_fmt(cell['static'])} & {_fmt(cell['rga'])} & {_fmt(cell['rga_plus'])} & "
            rf"{cell['best_name']} & {_fmt(cell['best_roc'])} & "
            rf"{_fmt(cell['delta_plus_vs_best'])} \\"
        )
    rows += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("docs/research/tables/milestone2_cross_benchmark.tex"),
    )
    parser.add_argument("--repo-root", type=Path, default=Path("."))
    args = parser.parse_args()

    table = render_table(args.repo_root)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(table, encoding="utf-8")
    print(f"Wrote {args.output}")
    print(table)


if __name__ == "__main__":
    main()
