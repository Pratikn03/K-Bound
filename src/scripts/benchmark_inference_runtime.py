"""Measure RGA's inference-time overhead vs. static attention.

Reviewer-requested benchmark (manuscript review v2, OVERALL_REVIEW_AND_PLAN
Phase 3.6): RGA adds reliability computation per batch — quantify the
overhead so the paper can state it explicitly.

The script runs three configurations against synthetic data of the same
shape used in the RealFusion-LA benchmark, with multiple repetitions for
mean/std:

  1. Static attention      — baseline (no reliability computation).
  2. RGA, batch-level gate  — current paper configuration.
  3. RGA, per-sample gate   — paper r_{i,d} formalism (always runs both paths).

Output: JSON + LaTeX table at ``--output`` paths.

Usage
-----
python -m src.scripts.benchmark_inference_runtime \
    --output experiments/fusion/runtime_benchmark.json \
    --latex docs/research/tables/rga_runtime_overhead.tex
"""

from __future__ import annotations

import argparse
import json
import statistics
import time
from pathlib import Path

import numpy as np
import torch

from uais.fusion.attention.cross_modal_attention import AttentionFusionModel
from uais.fusion.attention.reliability_estimator import ReliabilityEstimator


def _build_synthetic_inputs(
    n_samples: int,
    n_domains: int,
    n_features: int,
    score_index: int,
    seed: int = 42,
):
    rng = np.random.default_rng(seed)
    val_feat = rng.normal(size=(n_samples, n_domains, n_features)).astype(np.float32)
    val_feat[..., score_index] = np.clip(val_feat[..., score_index] * 0.2 + 0.5, 0.05, 0.95)
    test_feat = rng.normal(size=(n_samples, n_domains, n_features)).astype(np.float32)
    test_feat[..., score_index] = np.clip(test_feat[..., score_index] * 0.2 + 0.5, 0.05, 0.95)
    masks = np.zeros((n_samples, n_domains), dtype=bool)
    val_labels = (val_feat[:, 0, score_index] > 0.5).astype(np.float32)
    return val_feat, test_feat, masks, val_labels


def _build_model_and_estimator(n_domains: int, n_features: int, score_index: int):
    model = AttentionFusionModel(
        num_domains=n_domains,
        input_dim=n_features,
        embed_dim=64,
        num_heads=8,
        num_layers=1,
        dropout=0.0,
        use_confidence=False,
        use_input_confidence=False,
    )
    model.eval()
    estimator = ReliabilityEstimator(
        domain_order=[f"d{i}" for i in range(n_domains)],
        score_index=score_index,
        ece_weight=0.45,
        ks_weight=0.35,
        sharpness_weight=0.20,
        gate_threshold=0.66,
    )
    return model, estimator


def _time_static(model, features, masks, device, n_repeats: int, batch_size: int):
    feat_t = torch.tensor(features, dtype=torch.float32, device=device)
    mask_t = torch.tensor(masks, dtype=torch.bool, device=device)
    times = []
    with torch.no_grad():
        for _ in range(n_repeats):
            start = time.perf_counter()
            for s in range(0, len(features), batch_size):
                e = min(s + batch_size, len(features))
                model(feat_t[s:e], key_padding_mask=mask_t[s:e])
            times.append(time.perf_counter() - start)
    return times


def _time_rga(model, estimator, features, masks, device, n_repeats: int, batch_size: int,
              per_sample_gating: bool):
    # Lazy import to avoid script-level cycles
    from src.scripts.run_breakthrough_experiment import _predict_craf_with_stats

    times = []
    for _ in range(n_repeats):
        start = time.perf_counter()
        _predict_craf_with_stats(
            model, estimator, features, masks, device,
            batch_size=batch_size,
            clean_gate_threshold=0.66,
            per_sample_gating=per_sample_gating,
        )
        times.append(time.perf_counter() - start)
    return times


def _summary(times: list[float]) -> dict:
    return {
        "mean_ms": float(statistics.mean(times) * 1000),
        "std_ms": float(statistics.stdev(times) * 1000) if len(times) > 1 else 0.0,
        "min_ms": float(min(times) * 1000),
        "max_ms": float(max(times) * 1000),
        "n_runs": int(len(times)),
    }


def _write_latex_table(results: dict, path: Path) -> None:
    static = results["static"]
    rga_batch = results["rga_batch"]
    rga_sample = results["rga_per_sample"]
    static_ms = static["mean_ms"]
    overhead_batch = (rga_batch["mean_ms"] - static_ms) / static_ms * 100.0
    overhead_sample = (rga_sample["mean_ms"] - static_ms) / static_ms * 100.0

    lines = [
        "% Auto-generated by benchmark_inference_runtime.py",
        r"\begin{tabular}{lccc}",
        r"\toprule",
        r"\textbf{Method} & \textbf{Mean inference (ms)} & \textbf{Std (ms)} & "
        r"\textbf{Overhead vs. static} \\",
        r"\midrule",
        rf"Static attention & {static_ms:.2f} & {static['std_ms']:.2f} & --- \\",
        rf"RGA (batch-level gate) & {rga_batch['mean_ms']:.2f} & {rga_batch['std_ms']:.2f} & "
        rf"{overhead_batch:+.1f}\,\% \\",
        rf"RGA (per-sample gate) & {rga_sample['mean_ms']:.2f} & {rga_sample['std_ms']:.2f} & "
        rf"{overhead_sample:+.1f}\,\% \\",
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--n-samples", type=int, default=4000)
    parser.add_argument("--n-domains", type=int, default=4)
    parser.add_argument("--n-features", type=int, default=10)
    parser.add_argument("--score-index", type=int, default=0)
    parser.add_argument("--batch-size", type=int, default=256)
    parser.add_argument("--n-repeats", type=int, default=5)
    parser.add_argument("--n-warmup", type=int, default=2)
    parser.add_argument("--output", type=Path, default=Path("experiments/fusion/runtime_benchmark.json"))
    parser.add_argument("--latex", type=Path, default=Path("docs/research/tables/rga_runtime_overhead.tex"))
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    device = torch.device("cpu")
    val_feat, test_feat, masks, val_labels = _build_synthetic_inputs(
        args.n_samples, args.n_domains, args.n_features, args.score_index, args.seed
    )
    model, estimator = _build_model_and_estimator(args.n_domains, args.n_features, args.score_index)
    estimator.fit(val_feat, masks, val_labels)

    # Warm-up — JIT / kernel selection / cache warming
    for _ in range(args.n_warmup):
        _time_static(model, test_feat, masks, device, n_repeats=1, batch_size=args.batch_size)
        _time_rga(model, estimator, test_feat, masks, device, n_repeats=1,
                  batch_size=args.batch_size, per_sample_gating=False)

    static_times = _time_static(model, test_feat, masks, device, args.n_repeats, args.batch_size)
    rga_batch_times = _time_rga(model, estimator, test_feat, masks, device,
                                args.n_repeats, args.batch_size, per_sample_gating=False)
    rga_sample_times = _time_rga(model, estimator, test_feat, masks, device,
                                 args.n_repeats, args.batch_size, per_sample_gating=True)

    results = {
        "config": {
            "n_samples": args.n_samples,
            "n_domains": args.n_domains,
            "n_features": args.n_features,
            "batch_size": args.batch_size,
            "n_repeats": args.n_repeats,
            "n_warmup": args.n_warmup,
            "device": str(device),
        },
        "static": _summary(static_times),
        "rga_batch": _summary(rga_batch_times),
        "rga_per_sample": _summary(rga_sample_times),
    }

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(results, indent=2))
    _write_latex_table(results, args.latex)

    print(json.dumps(results, indent=2))
    print(f"\nWrote JSON to {args.output}")
    print(f"Wrote LaTeX table to {args.latex}")


if __name__ == "__main__":
    main()
