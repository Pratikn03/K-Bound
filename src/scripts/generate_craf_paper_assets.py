def _finite(value: Any) -> bool:
    return value is not None and isinstance(value, (int, float)) and math.isfinite(float(value))


def _fmt(value: Any, digits: int = 3) -> str:
    if not _finite(value):
        return "--"
    return f"{float(value):.{digits}f}"


def _fmt_pm(value: Any, std: Any, digits: int = 4) -> str:
    if not _finite(value):
        return "--"
    if not _finite(std) or abs(float(std)) < 0.5 * 10 ** (-digits):
        return _fmt(value, digits)
    return rf"{_fmt(value, digits)}$\pm${_fmt(std, digits)}"


def _fmt_ci(low: Any, high: Any, digits: int = 4) -> str:
    if not _finite(low) or not _finite(high):
        return "--"
    return rf"[{_fmt(low, digits)}, {_fmt(high, digits)}]"


def _fmt_pm_ci(vals: dict[str, Any], metric: str, digits: int = 4) -> str:
    rendered = _fmt_pm(vals.get(metric), vals.get(f"{metric}_std"), digits=digits)
    ci = _fmt_ci(vals.get(f"{metric}_ci_low"), vals.get(f"{metric}_ci_high"), digits=digits)
    return rendered if ci == "--" else rf"{rendered} {ci}"


def _latex_text(value: str) -> str:
    return value.replace("_", r"\_")


def _bold_best(
    rows: list[tuple[str, str, dict[str, Any]]],
    metric: str,
    higher_is_better: bool = True,
    digits: int = 4,
) -> dict[str, str]:
    values = [(key, vals.get(metric)) for key, _, vals in rows if _finite(vals.get(metric))]
    if not values:
        return {key: _fmt_pm_ci(vals, metric, digits=digits) for key, _, vals in rows}
    best_value = max(v for _, v in values) if higher_is_better else min(v for _, v in values)
    out: dict[str, str] = {}
    for key, _, vals in rows:
        value = vals.get(metric)
        rendered = _fmt_pm_ci(vals, metric, digits=digits)
        if _finite(value) and abs(float(value) - float(best_value)) <= max(1e-12, 0.5 * 10 ** (-digits)):
            rendered = rf"\textbf{{{rendered}}}"
        out[key] = rendered
    return out


def _load(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _clean_rows(data: dict[str, Any]) -> list[tuple[str, str, dict[str, Any]]]:
    if data.get("clean_metric_summary"):
        output = []
        summary = data["clean_metric_summary"]
        for key, label in METHOD_ORDER:
            if key not in summary:
                continue
            metrics: dict[str, Any] = {}
            for metric, vals in summary[key].items():
                metrics[metric] = vals.get("mean")
                metrics[f"{metric}_std"] = vals.get("std")
                metrics[f"{metric}_ci_low"] = vals.get("ci_low")
                metrics[f"{metric}_ci_high"] = vals.get("ci_high")
                metrics[f"{metric}_n"] = vals.get("n")
            output.append((key, label, metrics))
        return output

    seed_rows = data["table_1_clean_performance"]
    output = []
    for key, label in METHOD_ORDER:
        metric_names = sorted({metric for row in seed_rows for metric in row[key]})
        metrics: dict[str, Any] = {}
        for metric in metric_names:
            values = [row[key].get(metric) for row in seed_rows]
            values = [float(v) for v in values if _finite(v)]
            if not values:
                continue
            metrics[metric] = float(np.mean(values))
            metrics[f"{metric}_std"] = float(np.std(values))
            if len(values) == 1:
                metrics[f"{metric}_ci_low"] = values[0]
                metrics[f"{metric}_ci_high"] = values[0]
            else:
                metrics[f"{metric}_ci_low"] = float(np.percentile(values, 2.5))
                metrics[f"{metric}_ci_high"] = float(np.percentile(values, 97.5))
        output.append((key, label, metrics))
    return output


def write_domain_scorer_table(metadata: dict[str, Any], out_dir: Path) -> None:
    metrics = metadata.get("domain_scorer_metrics", {})
    if not metrics:
        return
    lines = [
        GENERATED_COMMENT,
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r"\textbf{Domain} & \textbf{Rows} & \textbf{Pos. rate} & \textbf{OOF ROC} & \textbf{OOF PR} \\",
        r"\midrule",
    ]
    for domain in metadata.get("domain_order", sorted(metrics)):
        vals = metrics[domain]
        lines.append(
            rf"{_latex_text(domain)} & {int(vals['rows'])} & {_fmt(vals['positive_rate'])} & "
            rf"{_fmt(vals['oof_roc_auc'], 4)} & {_fmt(vals['oof_pr_auc'], 4)} \\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    _write(out_dir / "real_domain_scorers.tex", "\n".join(lines))


