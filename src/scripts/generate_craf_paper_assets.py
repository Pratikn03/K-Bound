    write_drift_table(data, args.tables_dir)
    write_calibration_table(data, args.tables_dir)
    write_adversarial_table(data, args.tables_dir)
    write_tau_sweep_table(data, args.tables_dir)
    write_component_ablation_table(data, args.tables_dir)
    write_failure_case_table(data, args.tables_dir)
    if metadata:
        write_domain_scorer_table(metadata, args.tables_dir)
        write_benchmark_metadata_table(metadata, args.tables_dir)
    if paired_data:
        write_named_clean_table(paired_data, args.tables_dir, "mvtec3d_clean_results.tex")
    if paired_metadata:
        write_paired_benchmark_metadata_table(paired_metadata, args.tables_dir)

    _set_style()
