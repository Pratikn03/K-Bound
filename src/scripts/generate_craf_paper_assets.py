def _set_style() -> None:
    plt.rcParams.update(
        {
            "font.size": 10,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "figure.dpi": 150,
            "savefig.dpi": 250,
            "figure.facecolor": "white",
            "axes.facecolor": "white",
            "savefig.facecolor": "white",
        }
    )


def _save(fig: plt.Figure, path: Path) -> None:
    fig.patch.set_facecolor("white")
    fig.savefig(path, facecolor="white", edgecolor="none", transparent=False)


def plot_clean_benchmark(data: dict[str, Any], out_dir: Path) -> None:
    rows = _clean_rows(data)
    labels = [label for _, label, _ in rows]
    roc = [vals["roc_auc"] for _, _, vals in rows]
    pr = [vals["pr_auc"] for _, _, vals in rows]
    x = np.arange(len(labels))
    width = 0.36

    fig, ax = plt.subplots(figsize=(8.2, 3.4))
    ax.bar(x - width / 2, roc, width, label="ROC-AUC", color="#2f6f73")
    ax.bar(x + width / 2, pr, width, label="PR-AUC", color="#c46a32")
    lower = 0.95 if min(roc + pr) > 0.95 else 0.0
    ax.set_ylim(lower, 1.0)
    ax.set_ylabel("Score")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=25, ha="right")
    ax.legend(frameon=False, ncol=2)
    ax.grid(axis="y", alpha=0.22)
    fig.tight_layout()
    _save(fig, out_dir / "rga_clean_benchmark.png")
    plt.close(fig)


